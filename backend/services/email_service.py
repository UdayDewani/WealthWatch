"""
Gmail SMTP email service — sends portfolio report HTML emails.
Uses Python's built-in smtplib with STARTTLS on port 587.
No additional packages required.
"""
from __future__ import annotations

import asyncio
import logging
import smtplib
from datetime import datetime, timezone
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

from config import GMAIL_SENDER, GMAIL_APP_PASSWORD

logger = logging.getLogger("email_service")

_SMTP_HOST = "smtp.gmail.com"
_SMTP_PORT = 587


def _send_sync(to_email: str, client_name: str, html_body: str) -> bool:
    """Synchronous send — run via asyncio.to_thread."""
    if not GMAIL_SENDER or not GMAIL_APP_PASSWORD:
        logger.error("Gmail credentials not configured — set GMAIL_SENDER and GMAIL_APP_PASSWORD in .env")
        return False

    today = datetime.now(tz=timezone.utc).strftime("%B %d, %Y")

    msg = MIMEMultipart("alternative")
    msg["Subject"] = f"Your WealthWatch Portfolio Report — {today}"
    msg["From"]    = f"WealthWatch <{GMAIL_SENDER}>"
    msg["To"]      = to_email

    # Plain-text fallback for email clients that don't render HTML
    plain = (
        f"Dear {client_name},\n\n"
        "Your personalized portfolio report has been generated by WealthWatch AI.\n"
        "Please view this email in an HTML-capable mail client to see the full report.\n\n"
        "WealthWatch Team\n"
        "This report is AI-generated and for informational purposes only."
    )
    msg.attach(MIMEText(plain, "plain"))
    msg.attach(MIMEText(html_body, "html"))

    try:
        with smtplib.SMTP(_SMTP_HOST, _SMTP_PORT, timeout=30) as server:
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(GMAIL_SENDER, GMAIL_APP_PASSWORD)
            server.sendmail(GMAIL_SENDER, to_email, msg.as_string())
        logger.info("Portfolio report sent to %s", to_email)
        return True
    except smtplib.SMTPAuthenticationError:
        logger.error("Gmail authentication failed — check GMAIL_APP_PASSWORD in .env")
        return False
    except Exception as exc:
        logger.error("Failed to send email to %s: %s", to_email, exc)
        return False


async def send_report_email(to_email: str, client_name: str, html_body: str) -> bool:
    """Send portfolio report email asynchronously (runs SMTP in thread pool)."""
    return await asyncio.to_thread(_send_sync, to_email, client_name, html_body)
